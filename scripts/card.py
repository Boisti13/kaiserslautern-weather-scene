#!/usr/bin/env python3
"""Write card/weather-card.yaml: the dashboard card with card/layers.js inside.

Run:  python3 scripts/card.py [--check]
The card is a vertical-stack-in-card holding a Bubble Card button (the scene)
and a weather-forecast card. Its Bubble `styles` paint the scene:
`background: ${<layers.js>}` picks the layers from sensor.overview_sky.
--check exits 1 if card/weather-card.yaml is out of date (used by CI).
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
card = json.loads((ROOT / "card" / "card.template.json").read_text())
layers = (ROOT / "card" / "layers.js").read_text().strip()
assert "`" not in layers, "layers.js must not use backticks (Bubble wraps styles in a template literal)"
bubble = card["cards"][0]
bubble["styles"] = bubble["styles"].replace("__LAYERS__", layers)


class Dumper(yaml.SafeDumper):
    pass


def text(dumper, s):
    style = "|" if "\n" in s else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style=style)


Dumper.add_representer(str, text)
out = ("# Kaiserslautern weather scene: generated by scripts/card.py from card/card.template.json\n"
       "# and card/layers.js; paste into a dashboard (Edit card > Show code editor).\n"
       + yaml.dump(card, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=200))
target = ROOT / "card" / "weather-card.yaml"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != out:
        sys.exit("card/weather-card.yaml is out of date: run python3 scripts/card.py")
    print("card/weather-card.yaml is up to date")
else:
    target.write_text(out)
    print("wrote", target.relative_to(ROOT))
